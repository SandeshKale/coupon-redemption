/**
 * Generates test-vectors/luhn32.json (1,000 deterministic codes) and the matching
 * pgTAP file so the TS and SQL Luhn implementations are checked against the same data.
 * Run: pnpm --filter @24m/shared vectors
 */
import { writeFileSync } from 'node:fs';

import { ALPHABET } from '../src/alphabet.ts';
import { luhn32CheckChar } from '../src/luhn32.ts';

let seed = 0x24_4d_24;
function next(): number {
  // xorshift32: deterministic, good enough for fixtures.
  seed ^= seed << 13;
  seed ^= seed >>> 17;
  seed ^= seed << 5;
  return seed >>> 0;
}

const vectors: { payload: string; check: string }[] = [];
for (let i = 0; i < 1000; i += 1) {
  let payload = '';
  for (let j = 0; j < 12; j += 1) payload += ALPHABET.charAt(next() & 31);
  vectors.push({ payload, check: luhn32CheckChar(payload) });
}

const root = new URL('../../../', import.meta.url);
writeFileSync(
  new URL('packages/shared/test-vectors/luhn32.json', root),
  `${JSON.stringify(vectors, null, 2)}\n`,
);

const values = vectors.map((v) => `  ('${v.payload}', '${v.check}')`).join(',\n');
const sql = `-- GENERATED by packages/shared/scripts/gen-vectors.ts. Do not edit.
begin;
select plan(2);

create temp table luhn_vectors (payload text, check_char text) on commit drop;
insert into luhn_vectors values
${values};

select is(
  (select count(*)::int from luhn_vectors where public.luhn32_check_char(payload) <> check_char),
  0,
  'SQL luhn32_check_char matches all 1,000 shared TypeScript vectors'
);
select is(
  (select count(*)::int from luhn_vectors where not public.luhn32_valid(payload || check_char)),
  0,
  'SQL luhn32_valid accepts all 1,000 shared vectors'
);

select * from finish();
rollback;
`;
writeFileSync(new URL('supabase/tests/005_luhn_vectors.test.sql', root), sql);
